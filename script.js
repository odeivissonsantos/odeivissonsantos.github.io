// ============ APLICAR TRADUÇÕES ============
function applyTranslations(lang) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key] != null) {
      el.innerHTML = translations[lang][key];
    }
  });
  document.documentElement.lang = lang;
  document.getElementById("caseTreinexBody").innerHTML = cases[lang].treinex;
  document.getElementById("caseCentralBody").innerHTML = cases[lang].central;
  document.getElementById("caseTracoBody").innerHTML = cases[lang].traco;
}

// ============ TEMA ============
const themeToggle = document.getElementById("themeToggle");
function setTheme(theme) {
  document.documentElement.setAttribute("data-theme", theme);
  const icon = themeToggle.querySelector("i");
  icon.className = theme === "dark" ? "bi bi-moon-stars" : "bi bi-sun";
  localStorage.setItem("theme", theme);
}
themeToggle.addEventListener("click", () => {
  const current = document.documentElement.getAttribute("data-theme");
  setTheme(current === "dark" ? "light" : "dark");
});

// ============ IDIOMA ============
const langSelect = document.getElementById("languageSelect");
langSelect.addEventListener("change", (e) => {
  localStorage.setItem("lang", e.target.value);
  applyTranslations(e.target.value);
});

// ============ INIT ============
window.addEventListener("DOMContentLoaded", () => {
  setTheme(localStorage.getItem("theme") || "dark");
  const lang = localStorage.getItem("lang") || "pt";
  langSelect.value = lang;
  applyTranslations(lang);

  // Reveal on scroll
  const revealEls = document.querySelectorAll(
    ".section-head, .service-card, .value-card, .project-card, .step-card, .info-card, .edu-card, .contact-box, .stat-num"
  );
  revealEls.forEach((el) => el.classList.add("reveal"));
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("in");
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 }
  );
  revealEls.forEach((el) => io.observe(el));
});

// ============ NAVBAR + BACK TO TOP + ACTIVE LINK ============
const nav = document.querySelector(".site-nav");
const backToTop = document.getElementById("backToTop");
const sections = [...document.querySelectorAll("section[id], header[id]")];
const navLinks = [...document.querySelectorAll(".site-nav .nav-link")];

backToTop.addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));

window.addEventListener("scroll", () => {
  const y = window.scrollY;
  nav.classList.toggle("scrolled", y > 40);
  backToTop.classList.toggle("show", y > 600);

  let currentId = "";
  sections.forEach((sec) => {
    if (y >= sec.offsetTop - 140) currentId = sec.id;
  });
  navLinks.forEach((link) => {
    link.classList.toggle("active", link.getAttribute("href") === `#${currentId}`);
  });
});
